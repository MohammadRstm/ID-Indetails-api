namespace ID_Indetails.api.Models;

/// <summary>Execution only: a material delivery or purchase on a site project.</summary>
public class ProjectMaterial
{
    public long Id { get; set; }

    public long ProjectId { get; set; }

    public string Name { get; set; } = string.Empty;

    public decimal Quantity { get; set; }

    /// <summary>Open vocabulary (tonne, m³, bag, …).</summary>
    public string Unit { get; set; } = "piece";

    public decimal UnitCost { get; set; }

    public string Currency { get; set; } = "USD";

    public string Category { get; set; } = "other";

    public string? Supplier { get; set; }

    public string? Note { get; set; }

    /// <summary>Generated by MySQL as quantity × unit cost; never written by the app.</summary>
    public decimal Total { get; private set; }

    public DateTime AddedAt { get; set; }

    public long AddedById { get; set; }

    public DateTime? UpdatedAt { get; set; }

    public DateTime? DeletedAt { get; set; }

    public Project Project { get; set; } = null!;
}
