using ID_Indetails.api.Enums;

namespace ID_Indetails.api.Models;

/// <summary>
/// Cash received from a client. Billing is a separate ledger: payments never change a project's
/// agreed revenue, profit or margin, but they are a period's revenue (money received, on the day
/// it arrived) in the Financials summary and the company overview. Payments are voided, never deleted.
/// </summary>
public class Payment
{
    public long Id { get; set; }

    public long ProjectId { get; set; }

    public long ClientId { get; set; }

    /// <summary>Null for a payment held on account.</summary>
    public long? InvoiceId { get; set; }

    /// <summary>The company account label it is filed under; null when none. An archived label stays on what carries it.</summary>
    public long? AccountLabelId { get; set; }

    /// <summary>
    /// The payment taken when the project was created (Execution). At most one live
    /// initial payment per project.
    /// </summary>
    public bool IsInitial { get; set; }

    /// <summary>
    /// Generated by MySQL: the project id for a live (not voided) initial payment, otherwise
    /// null. Its unique index enforces one live initial payment per project. Never written.
    /// </summary>
    public long? InitialForProjectId { get; private set; }

    /// <summary>Amount in the currency it was received in.</summary>
    public decimal Amount { get; set; }

    public string Currency { get; set; } = "USD";

    /// <summary>Units of <see cref="Currency"/> per USD, as confirmed on the day of receipt.</summary>
    public decimal FxRate { get; set; } = 1m;

    public decimal AmountUsd { get; set; }

    /// <summary>
    /// The TVA inside <see cref="AmountUsd"/>, at the project's rate when it was recorded. Money reports count the
    /// rest (net); billing counts the whole amount, since TVA is part of what the client owes.
    /// </summary>
    public decimal TvaUsd { get; set; }

    public DateOnly ReceivedOn { get; set; }

    public PaymentMethod Method { get; set; }

    public string? Reference { get; set; }

    public string? Note { get; set; }

    public DateTime RecordedAt { get; set; }

    public long? RecordedById { get; set; }

    public DateTime? VoidedAt { get; set; }

    public string? VoidReason { get; set; }

    public long? VoidedById { get; set; }

    public Project Project { get; set; } = null!;

    public Client Client { get; set; } = null!;

    public Invoice? Invoice { get; set; }

    public AccountLabel? AccountLabel { get; set; }
}
