namespace ID_Indetails.api.Extensions;

public static class ApplicationServiceCollectionExtensions
{
    /// <summary>Repositories, services and their settings.</summary>
    public static IServiceCollection AddApplicationServices(this IServiceCollection services)
    {
        services.AddOptions<CompanyOptions>().BindConfiguration(CompanyOptions.SectionName)
            .ValidateDataAnnotations()
            .Validate(o => TimeZoneInfo.TryFindSystemTimeZoneById(o.TimeZone, out _), "Company:TimeZone is not a known time zone.")
            .ValidateOnStart();
        services.AddOptions<InvitationOptions>().BindConfiguration(InvitationOptions.SectionName).ValidateDataAnnotations().ValidateOnStart();
        services.AddOptions<FrontendOptions>().BindConfiguration(FrontendOptions.SectionName).ValidateDataAnnotations().ValidateOnStart();
        services.AddOptions<EmailOptions>().BindConfiguration(EmailOptions.SectionName).ValidateDataAnnotations().ValidateOnStart();
        services.AddOptions<NotificationSchedulerOptions>().BindConfiguration(NotificationSchedulerOptions.SectionName)
            .ValidateDataAnnotations()
            .ValidateOnStart();

        services.AddMemoryCache();
        services.AddSingleton<IClock, SystemClock>();

        // Repositories
        services.AddScoped<IUnitOfWork, UnitOfWork>();
        services.AddScoped<IUserRepository, UserRepository>();
        services.AddScoped<IRefreshTokenRepository, RefreshTokenRepository>();
        services.AddScoped<IPermissionRepository, PermissionRepository>();
        services.AddScoped<IInvitationRepository, InvitationRepository>();
        services.AddScoped<ITeamRepository, TeamRepository>();
        services.AddScoped<IActivityEventRepository, ActivityEventRepository>();
        services.AddScoped<IActivityFeedRepository, ActivityFeedRepository>();
        services.AddScoped<IEmployeeRepository, EmployeeRepository>();
        services.AddScoped<IProjectFinanceRepository, ProjectFinanceRepository>();
        services.AddScoped<ICompanyRepository, CompanyRepository>();
        services.AddScoped<IScheduleRepository, ScheduleRepository>();
        services.AddScoped<IOverheadRepository, OverheadRepository>();
        services.AddScoped<ICompanyFinanceRepository, CompanyFinanceRepository>();
        services.AddScoped<IPayrollRepository, PayrollRepository>();
        services.AddScoped<IHourExcuseRepository, HourExcuseRepository>();
        services.AddScoped<IClientRepository, ClientRepository>();
        services.AddScoped<IProjectRepository, ProjectRepository>();
        services.AddScoped<IRequirementRepository, RequirementRepository>();
        services.AddScoped<IExpenseRepository, ExpenseRepository>();
        services.AddScoped<IBillingSettingsRepository, BillingSettingsRepository>();
        services.AddScoped<IExchangeRateRepository, ExchangeRateRepository>();
        services.AddScoped<IInvoiceRepository, InvoiceRepository>();
        services.AddScoped<IPaymentRepository, PaymentRepository>();
        services.AddScoped<INotificationRepository, NotificationRepository>();
        services.AddScoped<IDomainSettingsRepository, DomainSettingsRepository>();
        services.AddScoped<IWorkEntryRepository, WorkEntryRepository>();
        services.AddScoped<IWorkEntryCommentRepository, WorkEntryCommentRepository>();
        services.AddScoped<IMeetingRepository, MeetingRepository>();
        services.AddScoped<IReportRepository, ReportRepository>();
        services.AddScoped<IMaterialRepository, MaterialRepository>();
        services.AddScoped<ILabourRepository, LabourRepository>();
        services.AddScoped<IStatementRepository, StatementRepository>();
        services.AddScoped<ISiteRecordsRepository, SiteRecordsRepository>();

        // Services
        services.AddSingleton<IPasswordService, PasswordService>();
        services.AddSingleton<IAccessTokenService, AccessTokenService>();
        services.AddScoped<IPermissionService, PermissionService>();
        services.AddScoped<ISessionService, SessionService>();
        services.AddScoped<IAuthService, AuthService>();
        services.AddScoped<IInvitationService, InvitationService>();
        services.AddScoped<IPermissionManagementService, PermissionManagementService>();
        services.AddScoped<IEmployeeService, EmployeeService>();
        services.AddScoped<IProjectFinanceService, ProjectFinanceService>();
        services.AddScoped<ICompanySettingsService, CompanySettingsService>();
        services.AddScoped<IWorkingTimeService, WorkingTimeService>();
        services.AddScoped<IScheduleService, ScheduleService>();
        services.AddScoped<IOverheadService, OverheadService>();
        services.AddScoped<ICompanyOverviewService, CompanyOverviewService>();
        services.AddScoped<ISalaryService, SalaryService>();
        services.AddScoped<IHourExcuseService, HourExcuseService>();
        services.AddScoped<IProjectPayService, ProjectPayService>();
        services.AddScoped<ITeamService, TeamService>();
        services.AddScoped<ISetupService, SetupService>();
        services.AddScoped<IClientService, ClientService>();
        services.AddScoped<IProjectService, ProjectService>();
        services.AddScoped<IProjectProgress, ProjectProgress>();
        services.AddScoped<IProjectStatusService, ProjectStatusService>();
        services.AddScoped<IRequirementService, RequirementService>();
        services.AddScoped<IExpenseService, ExpenseService>();
        services.AddScoped<IBillingSettingsService, BillingSettingsService>();
        services.AddScoped<IInvoiceService, InvoiceService>();
        services.AddScoped<IPaymentService, PaymentService>();
        services.AddScoped<IDomainSettingsService, DomainSettingsService>();
        services.AddScoped<IWorkLogNotifier, WorkLogNotifier>();
        services.AddScoped<IWorkEntryService, WorkEntryService>();
        services.AddScoped<IWorkEntryQueryService, WorkEntryQueryService>();
        services.AddScoped<IWorkEntryCommentService, WorkEntryCommentService>();
        services.AddScoped<IMyWorkService, MyWorkService>();
        services.AddScoped<IWorkInsightsService, WorkInsightsService>();
        services.AddScoped<IMeetingService, MeetingService>();
        services.AddScoped<IReportService, ReportService>();
        services.AddScoped<IActivityFeedService, ActivityFeedService>();
        services.AddScoped<INotificationSender, NotificationSender>();
        services.AddScoped<INotificationService, NotificationService>();
        services.AddScoped<IProjectNotifier, ProjectNotifier>();
        services.AddScoped<IScheduledNotifications, ScheduledNotifications>();
        services.AddHostedService<NotificationScheduler>();
        services.AddScoped<IMaterialService, MaterialService>();
        services.AddScoped<ILabourService, LabourService>();
        services.AddScoped<IStatementService, StatementService>();
        services.AddScoped<ISiteRecordsService, SiteRecordsService>();
        services.AddScoped<ISiteMoneyService, SiteMoneyService>();
        services.AddSingleton<IEmailSender, SmtpEmailSender>();

        return services;
    }
}
